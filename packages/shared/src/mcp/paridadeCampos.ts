// do esquema (e dos objetos de dentro) de cada intenção com ferramenta, por onde o Claude o põe: `"ferramenta:caminho"`
// (o caminho na entrada da ferramenta, com `[]` para listas, `{}` para mapas e `.` para objetos), ou o motivo de ficar
// de fora. O teste `paridadeCampos.test.ts` compara esta tabela com o `shape` do zod de cada intenção e com a entrada de cada
// ferramenta: campo novo sem linha aqui, ou linha que aponta um caminho que a ferramenta não tem, reprova.
//
// Chave que termina em `*` vale para todo campo que começa pelo texto antes dele; no valor, o `*` repete o resto do
// caminho (`"zona.efeitos.*"` -> `"automacoes:zonas[].efeitos.*"`).

/** Campo que não precisa de caminho próprio: `interno` (id que o Claude troca por nome, valor que a sala preenche, campo antigo). */
export type CategoriaDeCampoFora = CategoriaFora | "interno";
export type CampoFora = { fora: CategoriaDeCampoFora; motivo: string };
/** `"ferramenta:caminho"` ou o motivo de ficar de fora. */
export type EntradaDeCampo = string | CampoFora;

const fora = (categoria: CategoriaDeCampoFora, motivo: string): CampoFora => ({
  fora: categoria,
  motivo,
});

